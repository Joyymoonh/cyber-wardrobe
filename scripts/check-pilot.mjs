import fs from 'node:fs';
const cfg=JSON.parse(fs.readFileSync('data/pilot/access.json','utf8'));
const base=process.argv[2]||'http://127.0.0.1:3001';
const request=(url,options={})=>fetch(url,{...options,signal:AbortSignal.timeout(20000)});
const page=await request(base+'/login');
const html=await page.text();
if(page.status!==200||!html.includes('/_next/'))throw new Error('Login page unavailable '+page.status);
const asset=html.match(/(?:src|href)="([^"]*\/_next\/static\/[^"]+)"/);
if(!asset)throw new Error('Missing frontend assets');
const staticResponse=await request(new URL(asset[1].replaceAll('&amp;','&'),base));
if(staticResponse.status!==200)throw new Error('Frontend assets unavailable');
const login=await request(base+'/api/auth/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email:cfg.email,password:cfg.password})});
if(login.status!==200)throw new Error('Login failed '+login.status);
const cookie=login.headers.get('set-cookie')?.split(';')[0];if(!cookie)throw new Error('Missing session');
if(!/; Secure/i.test(login.headers.get('set-cookie')))throw new Error('Session must be secure');
const items=await request(base+'/api/items',{headers:{cookie}});const data=await items.json();
if(items.status!==200||data.items.length<8)throw new Error('Wardrobe unavailable');
const denied=await request(base+'/api/items');if(denied.status!==401)throw new Error('Anonymous wardrobe access allowed');
const registration=await request(base+'/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email:'no@test.com',nickname:'no',password:'no-register-please'})});
if(registration.status!==403)throw new Error('Public registration is not closed');
const outfits=await request(base+'/api/outfits/generate',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({style:'sweet',season:'autumn',occasion:'约会',mode:'rule',count:3})});
const generated=await outfits.json();if(outfits.status!==200||!generated.outfits?.length)throw new Error('Outfit generation failed');
console.log(JSON.stringify({loginPage:'ok',frontendAssets:'ok',login:'ok',secureCookie:true,items:data.items.length,anonymousAccess:'blocked',registration:'closed',outfits:generated.outfits.length}));
